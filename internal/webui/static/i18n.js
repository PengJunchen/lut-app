  function translateKnownMessage(value, translate) {
    const message = String(value ?? '').trim();
    const key = knownBackendMessages.get(message);
    if (key) return translate(key);
    for (const language of ['zh-CN', 'en']) {
      for (const [messageKey, localized] of Object.entries(messages[language] || {})) {
        if (localized === message) return translate(messageKey);
      }
    }
    for (const language of ['zh-CN', 'en']) {
      for (const [messageKey, localized] of Object.entries(messages[language] || {})) {
        const names = [];
        const pattern = String(localized).replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\\\{([a-zA-Z0-9_]+)\\\}/g, (_, name) => {
          names.push(name);
          return '([\\s\\S]+?)';
        });
        if (!names.length) continue;
        const match = message.match(new RegExp(`^${pattern}$`));
        if (match) return translate(messageKey, Object.fromEntries(names.map((name, index) => [name, match[index + 1]])));
      }
    }
    const wrapped = [
      [/^读取文件夹选择请求失败：(.+)$/s, 'backend.readPicker'],
      [/^读取扫描选项失败：(.+)$/s, 'backend.readScanOptions'],
      [/^打开结果文件夹失败：(.+)$/s, 'backend.openOutputFailed'],
      [/^没有可用的起始文件夹：(.+)$/s, 'backend.startDirectory'],
      [/^文件夹选择失败：(.+)$/s, 'backend.pickerFailed'],
      [/^解析所选文件夹失败：(.+)$/s, 'backend.resolveFolder'],
      [/^所选文件夹不可用：(.+)$/s, 'backend.unavailableFolder'],
      [/^结果文件夹不可用：(.+)$/s, 'backend.outputFolderUnavailable'],
      [/^解析结果路径失败：(.+)$/s, 'backend.outputPathInvalid'],
      [/^读取请求失败: (.+)$/s, 'backend.requestRead'],
      [/^input directory is required$/i, 'backend.emptyInput'],
      [/^output directory cannot be the input directory$/i, 'backend.invalidOutput'],
      [/^unsupported look "?(standard|vivid)"? \(expected standard or vivid\)$/i, 'backend.invalidLook']
    ];
    for (const [pattern, wrappedKey] of wrapped) {
      const match = message.match(pattern);
      if (match) return translate(wrappedKey, {details: match[1] || ''});
    }
    return null;
  }

  function createI18n(initialLanguage = 'zh-CN') {
    let language = normalizeLanguage(initialLanguage) || 'zh-CN';
    const originalText = new WeakMap();
    const originalAttributes = new WeakMap();

    function t(key, values = {}) {
      const table = messages[language] || messages['zh-CN'];
      let value = table[key] ?? messages['zh-CN'][key] ?? key;
      return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
    }

    function apply(root = globalThis.document) {
      if (!root) return;
      const doc = root.nodeType === 9 ? root : root.ownerDocument;
      const documentElement = doc?.documentElement;
      if (documentElement) documentElement.lang = language;
      const walker = doc?.createTreeWalker(root, globalThis.NodeFilter?.SHOW_TEXT ?? 4);
      if (walker) {
        let node;
        while ((node = walker.nextNode())) {
          const parent = node.parentElement;
          if (!parent || parent.closest('script,style,code,pre,[data-i18n-ignore]')) continue;
          if (!originalText.has(node)) originalText.set(node, node.nodeValue);
          const source = String(originalText.get(node) || '');
          const trimmed = source.trim();
          const key = staticTextKeys[trimmed];
          if (!key) continue;
          const leading = source.match(/^\s*/)?.[0] || '';
          const trailing = source.match(/\s*$/)?.[0] || '';
          node.nodeValue = `${leading}${t(key)}${trailing}`;
        }
      }
      const elements = root.querySelectorAll ? [root, ...root.querySelectorAll('*')] : [];
      for (const element of elements) {
        let attributes = originalAttributes.get(element);
        if (!attributes) {
          attributes = new Map();
          originalAttributes.set(element, attributes);
        }
        for (const attribute of ['title', 'aria-label', 'placeholder']) {
          if (!element.hasAttribute?.(attribute)) continue;
          if (!attributes.has(attribute)) attributes.set(attribute, element.getAttribute(attribute));
          const key = staticAttributeKeys[attributes.get(attribute)];
          if (key) element.setAttribute(attribute, t(key));
        }
      }
    }

    return {
      t,
      get language() { return language; },
      setLanguage(value) {
        const next = normalizeLanguage(value);
        if (!next) return false;
        language = next;
        return true;
      },
      translateKnownMessage(value) {
        return translateKnownMessage(value, t);
      },
      apply
    };
  }

