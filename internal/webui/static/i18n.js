  function normalizeLanguage(value) {
    const language = String(value || '').trim().toLowerCase();
    if (language === 'en' || language.startsWith('en-')) return 'en';
    if (language === 'zh-cn' || language === 'zh' || language.startsWith('zh-')) return 'zh-CN';
    return null;
  }

  function preferredBrowserLanguage(storage, navigatorObject) {
    try {
      const saved = normalizeLanguage(storage?.getItem('dji-lut-language'));
      if (saved) return saved;
    } catch (_) { /* Local storage is optional and may be blocked. */ }
    const candidates = [navigatorObject?.language, ...(navigatorObject?.languages || [])];
    for (const candidate of candidates) {
      const detected = normalizeLanguage(candidate);
      if (detected) return detected;
    }
    return 'zh-CN';
  }

  function createNativeLanguageController({initialLanguage = 'zh-CN', save, onLanguage, onError} = {}) {
    let confirmed = normalizeLanguage(initialLanguage) || 'zh-CN';
    let desired = confirmed;
    let saving = false;

    function finishSave(target, error, response) {
      saving = false;
      if (!error) {
        const accepted = normalizeLanguage(typeof response === 'string' ? response : response?.language ?? response?.Language);
        if (accepted) confirmed = accepted;
        else error = new Error('Desktop language preference response was invalid');
      }

      if (error) {
        if (desired === target) {
          desired = confirmed;
          onLanguage?.(confirmed);
          onError?.(error);
          return;
        }
        if (desired === confirmed) {
          onLanguage?.(confirmed);
          return;
        }
      } else if (desired === target) {
        desired = confirmed;
        onLanguage?.(confirmed);
        return;
      } else if (desired === confirmed) {
        onLanguage?.(confirmed);
        return;
      }

      pump();
    }

    function pump() {
      if (saving || desired === confirmed || typeof save !== 'function') return;
      const target = desired;
      saving = true;
      Promise.resolve().then(() => save(target)).then(
        (response) => finishSave(target, null, response),
        (error) => finishSave(target, error)
      );
    }

    return {
      select(value) {
        const next = normalizeLanguage(value);
        if (!next) return false;
        desired = next;
        onLanguage?.(next);
        pump();
        return true;
      },
      setConfirmed(value) {
        const next = normalizeLanguage(value);
        if (!next || saving) return false;
        confirmed = next;
        desired = confirmed;
        onLanguage?.(confirmed);
        return true;
      },
      get confirmed() { return confirmed; },
      get desired() { return desired; },
      get pending() { return saving; }
    };
  }

